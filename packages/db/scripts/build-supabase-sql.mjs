// Builds supabase/setup.sql: the whole database (every Prisma migration, recorded the way
// `prisma migrate deploy` records them, plus row-level security and roles) as one script to
// paste into the Supabase SQL editor. Regenerate after adding a migration:
//   pnpm --filter @lms/db build:supabase-sql
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = join(root, "prisma/migrations");
const migrations = readdirSync(migrationsDir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

const literal = (s) => `'${s.replaceAll("'", "''")}'`;
// Stable ids, so regenerating the file only changes it when a migration changes.
const idFor = (name) => createHash("sha256").update(name).digest("hex").replace(/^(.{8})(.{4})(.{4})(.{4})(.{12}).*/, "$1-$2-$3-$4-$5");

const parts = [
  `-- Coaching LMS: complete database setup for a NEW, EMPTY Supabase project.
-- Generated by packages/db/scripts/build-supabase-sql.mjs; do not edit by hand.
--
-- 1. Replace the two passwords below with long random strings (letters and digits only).
--    They are the passwords of the app's own database logins, lms_app and lms_platform;
--    use the same ones in DATABASE_URL and DATABASE_URL_PLATFORM.
-- 2. Paste the whole file into Supabase → SQL Editor → New query, and press Run.
--
-- Everything runs in one transaction: if anything fails, nothing is changed.
-- Later schema changes are applied by the app's deploy step (prisma migrate deploy), which
-- sees these migrations as already applied.

BEGIN;

SELECT set_config('lms.app_password', 'CHANGE_ME_APP_PASSWORD', true);
SELECT set_config('lms.platform_password', 'CHANGE_ME_PLATFORM_PASSWORD', true);

DO $$
BEGIN
  IF current_setting('lms.app_password') LIKE 'CHANGE_ME%' OR current_setting('lms.platform_password') LIKE 'CHANGE_ME%' THEN
    RAISE EXCEPTION 'Set the two passwords at the top of this script first.';
  END IF;
  IF length(current_setting('lms.app_password')) < 16 OR length(current_setting('lms.platform_password')) < 16 THEN
    RAISE EXCEPTION 'Use passwords of at least 16 characters.';
  END IF;
  IF to_regclass('public._prisma_migrations') IS NOT NULL THEN
    RAISE EXCEPTION 'This database is already set up; new migrations are applied by the app''s deploy step.';
  END IF;
END $$;

-- Prisma's migration history table, so later deploys only apply newer migrations.
CREATE TABLE "_prisma_migrations" (
    "id"                    VARCHAR(36) PRIMARY KEY NOT NULL,
    "checksum"              VARCHAR(64) NOT NULL,
    "finished_at"           TIMESTAMPTZ,
    "migration_name"        VARCHAR(255) NOT NULL,
    "logs"                  TEXT,
    "rolled_back_at"        TIMESTAMPTZ,
    "started_at"            TIMESTAMPTZ NOT NULL DEFAULT now(),
    "applied_steps_count"   INTEGER NOT NULL DEFAULT 0
);`,
];

for (const name of migrations) {
  const sql = readFileSync(join(migrationsDir, name, "migration.sql"), "utf8");
  const checksum = createHash("sha256").update(sql).digest("hex");
  parts.push(
    `-- ════════ Migration ${name} ════════\n${sql.trim()}`,
    `INSERT INTO "_prisma_migrations" (id, checksum, migration_name, started_at, finished_at, applied_steps_count)\n` +
      `VALUES (${literal(idFor(name))}, ${literal(checksum)}, ${literal(name)}, now(), now(), 1);`,
  );
}

parts.push(
  `-- ════════ Row-level security, roles and grants (prisma/sql/rls.sql) ════════\n` +
    readFileSync(join(root, "prisma/sql/rls.sql"), "utf8").trim(),
  `-- ════════ App role passwords ════════
DO $$
BEGIN
  EXECUTE format('ALTER ROLE lms_app WITH LOGIN PASSWORD %L', current_setting('lms.app_password'));
  EXECUTE format('ALTER ROLE lms_platform WITH LOGIN PASSWORD %L', current_setting('lms.platform_password'));
END $$;

-- ════════ Private storage bucket for course files, logos and certificates ════════
-- 50 MB per file: the Supabase free plan's limit (keep MAX_UPLOAD_MB=50 on the API).
DO $$
BEGIN
  IF to_regclass('storage.buckets') IS NOT NULL THEN
    INSERT INTO storage.buckets (id, name, public, file_size_limit)
    VALUES ('lms-files', 'lms-files', false, 52428800)
    ON CONFLICT (id) DO NOTHING;
  END IF;
END $$;

COMMIT;

-- Done. Check: should list ${migrations.length} migrations and both roles.
SELECT migration_name FROM "_prisma_migrations" ORDER BY 1;
SELECT rolname, rolcanlogin, rolbypassrls FROM pg_roles WHERE rolname IN ('lms_app', 'lms_platform');`,
);

const out = join(root, "supabase/setup.sql");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, parts.join("\n\n") + "\n");
console.log(`Wrote ${out} (${migrations.length} migrations)`);
